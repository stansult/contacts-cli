"""List phone entries and remove selected surplus occurrences without guessing countries."""

import json
import sys
from collections import Counter
from copy import deepcopy

from .contact_matches import phone_key
from .core import CONTACT_FIELDS, _stable, contact_resource, contact_source, field_update_body
from .email_edit import is_primary
from .errors import SyncError
from .output import emit, emit_list
from .selection import review_selection


def phone_identity(entry):
    raw = phone_key(entry["value"])
    if raw is None:
        return None
    canonical = phone_key(entry.get("canonicalForm", ""))
    if canonical:
        if raw[1] and canonical[1] and raw[1] != canonical[1]:
            return None
        return canonical[0].removeprefix("+"), raw[1] or canonical[1]
    return raw[0].removeprefix("+"), raw[1]


def phone_entries(person):
    source = contact_source(person)
    entries = person.get("phoneNumbers", [])
    if not isinstance(entries, list):
        raise SyncError("Incomplete phone entries.")
    for entry in entries:
        if not isinstance(entry, dict) or not isinstance(entry.get("value"), str):
            raise SyncError("Invalid phone entry.")
        if any(
            key in entry and not isinstance(entry[key], str)
            for key in ("type", "canonicalForm", "formattedType")
        ):
            raise SyncError("Invalid phone entry details.")
        metadata = entry.get("metadata", {})
        if not isinstance(metadata, dict):
            raise SyncError("Invalid phone metadata.")
        field_source = metadata.get("source", {})
        if not isinstance(field_source, dict) or (
            field_source
            and (field_source.get("type") != "CONTACT" or field_source.get("id") != source["id"])
        ):
            raise SyncError("Contact contains phones from another source.")
    return deepcopy(entries)


def phone_text(entry):
    text = entry["value"]
    if entry.get("type"):
        text += f" — {entry['type']}"
    if is_primary(entry):
        text += " (primary)"
    return text


def phone_rows(entries):
    seen = {}
    rows = []
    for number, entry in enumerate(entries, 1):
        key = phone_identity(entry)
        text = phone_text(entry)
        if key is not None:
            if key in seen:
                text += f" [duplicate of #{seen[key]}]"
            else:
                seen[key] = number
        rows.append((number, text))
    return rows


def duplicate_phones(entries):
    groups = {}
    for index, entry in enumerate(entries):
        key = phone_identity(entry)
        if key is not None:
            groups.setdefault(key, []).append(index)
    removed, kept = [], []
    for indexes in groups.values():
        if len(indexes) < 2:
            continue
        survivor = next((i for i in indexes if is_primary(entries[i])), indexes[0])
        kept.append(survivor)
        removed.extend(i for i in indexes if i != survivor)
    return sorted(removed), kept


def phone_signature(entry):
    # Canonical form and translated labels are generated by Google, not editable values.
    return json.dumps(
        _stable({k: v for k, v in entry.items() if k not in {"canonicalForm", "formattedType"}}),
        sort_keys=True,
    )


def verify_phones(person, expected, saved):
    actual = phone_entries(saved)
    if contact_source(person)["id"] != contact_source(saved)["id"]:
        raise SyncError("Saved result refers to a different contact source.")
    if Counter(map(phone_signature, expected)) != Counter(map(phone_signature, actual)):
        raise SyncError("Saved phone entries do not match the preview.")
    required = Counter(phone_signature(e) for e in expected if is_primary(e))
    retained = Counter(phone_signature(e) for e in actual if is_primary(e))
    if required - retained:
        raise SyncError("A retained primary phone choice changed.")
    for field in CONTACT_FIELDS.split(","):
        if field not in {"phoneNumbers", "metadata"} and _stable(person.get(field, [])) != _stable(
            saved.get(field, [])
        ):
            raise SyncError(f"Contact field {field} changed during the update.")


def run_phone(args, api, confirm, heading):
    emit("Reading contact…")
    person = api.get_contact(contact_resource(args.contact))
    entries = phone_entries(person)
    emit(heading(person) + "\n", primary=False)
    if args.command == "list-phone":
        emit_list("Phone numbers", phone_rows(entries))
        return 0
    candidates, kept = duplicate_phones(entries)
    if not candidates:
        emit("No duplicate phone entries found; no changes made.")
        return 0
    choices = [(n, phone_text(entries[i])) for n, i in enumerate(candidates, 1)]
    emit_list(
        "Removing duplicate phone entries" if args.apply else "Proposed duplicate phone removals",
        choices,
    )
    emit_list(
        "Kept entries",
        [(len(choices) + n, phone_text(entries[i])) for n, i in enumerate(kept, 1)],
        note="Informational only; these numbers cannot be selected.",
    )
    expected = [e for i, e in enumerate(entries) if i not in candidates]
    count = len(candidates)

    def preview(selected):
        nonlocal expected, count
        indexes = {candidates[n - 1] for n in selected}
        expected = [e for i, e in enumerate(entries) if i not in indexes]
        count = len(indexes)
        field_update_body(person, "phoneNumbers", expected)
        if len(selected) != len(choices):
            emit_list(
                "Selected phone removals", [(n, text) for n, text in choices if n in selected]
            )
        emit("", primary=False)

    def question(_=None):
        return f"Remove {count} phone {'entry' if count == 1 else 'entries'}?"

    if (
        not args.apply
        and len(choices) > 1
        and all(s.isatty() for s in (sys.stdin, sys.stdout, sys.stderr))
    ):
        selected = review_selection(
            choices,
            noun="phone entries",
            unit=("entry", "entries"),
            heading="Selected phone removals",
            preview=preview,
            question=question,
            action="Remove selected phone entries",
        )
        if selected is None:
            emit("Cancelled; no changes made.")
            return 0
    elif not args.apply and not confirm(question()):
        emit("Preview only; no changes made. Use --apply to remove duplicate phone entries.")
        return 0
    body = field_update_body(person, "phoneNumbers", expected)
    api.apply_field_change(
        person, body, lambda saved: verify_phones(person, expected, saved), "phoneNumbers"
    )
    emit(f"Removed and verified {count} phone {'entry' if count == 1 else 'entries'}.")
    return 0
